from fractions import Fraction as F

import pytest

from strudelizer.core import Chord, Hit, Meta, Note, Section, Song, StrudelizerError, Track
from strudelizer.emitters.strudel import StrudelEmitter, _render_voice, _Item, _wrap
from strudelizer.passes.dedupe_bars import DedupeBars


def emit(song, **options):
    return StrudelEmitter().emit(song, options)


def notes(*specs, role="melody"):
    return Track(id="t", role=role, events=tuple(Note(F(s), F(d), p) for s, d, p in specs))


def test_header_and_setcps_odd_meter():
    song = Song(meta=Meta(title="X\nY", bpm=140, time_signature=(7, 8), source="a.mid"), tracks=(notes((0, 7, 60)),))
    code = emit(song)
    assert code.startswith("// X Y\n// Source: a.mid\n// Generated by Strudelizer 0.1.0 (profile: default)\n")
    assert "setcps(140/60/7)" in code
    assert code.endswith("\n")


def test_fractional_bpm_and_defaults():
    song = Song(meta=Meta(bpm=97.5), tracks=(notes((0, 4, 60)),))
    assert "setcps(97.5/60/4)" in emit(song)
    assert "setcps(120/60/4)" in emit(Song(tracks=(notes((0, 4, 60)),)))


def test_note_weights_rests_and_chord_tokens():
    song = Song(tracks=(notes((0, F(3, 2), 37), (2, 1, 60), (2, 1, 64), (2, 1, 67)),))
    assert 'note("c#2@3 ~ [c4,e4,g4]@2 ~ ~")' in emit(song)


def test_triplets_use_exact_weights():
    third = F(1, 3)
    song = Song(tracks=(notes((0, third, 64), (third, third, 67), (2 * third, third, 69), (1, 3, 60)),))
    assert 'note("e4 g4 a4 c4@9")' in emit(song)


def test_long_grids_merge_rests():
    items = [_Item(F(0), F(1, 32), "a", None), _Item(F(2), F(1, 32), "b", None)]
    assert _render_voice(items, F(4)) == "a ~@63 b ~@63"


def test_identical_steps_collapse():
    items = [_Item(F(i, 2), None, "hh", None) for i in range(8)]
    assert _render_voice(items, F(4)) == "hh*8"


def test_wrap_only_top_level():
    assert _wrap("[a3,c4]*2") == "[a3,c4]*2"
    assert _wrap("a b") == "[a b]"
    assert _wrap("a, b") == "[a, b]"
    assert _wrap("bd*4") == "bd*4"


def test_no_dedupe_writes_every_bar_dedupe_collapses():
    track = Track(id="k", role="drums", events=tuple(Hit(F(4 * b), "kick") for b in range(4)))
    song = Song(tracks=(track,))
    assert 's("<bd bd bd bd>")' in emit(song)
    assert 's("bd")' in emit(DedupeBars().run(song, {}))


def test_runs_and_period():
    def bar(b, p):
        return (4 * b, 4, p)

    # A A B B : runs, period 4
    song = DedupeBars().run(Song(tracks=(notes(bar(0, 60), bar(1, 60), bar(2, 62), bar(3, 62)),)), {})
    assert 'note("<c4!2 d4!2>")' in emit(song)
    # A B A B A B : period 2
    song = DedupeBars().run(Song(tracks=(notes(*[bar(b, 60 + 2 * (b % 2)) for b in range(6)]),)), {})
    assert 'note("<c4 d4>")' in emit(song)
    # A B A B A : period does not divide the song, write all bars
    song = DedupeBars().run(Song(tracks=(notes(*[bar(b, 60 + 2 * (b % 2)) for b in range(5)]),)), {})
    assert "c4 d4 c4 d4" in emit(song)


def test_many_bars_use_multiline_backticks():
    song = DedupeBars().run(Song(tracks=(notes(*[(4 * b, 4, 60 + b) for b in range(6)]),)), {})
    code = emit(song)
    assert "note(`<\n  c4 c#4 d4 d#4\n  e4 f4\n>`)" in code


def test_note_tied_across_barline_is_held():
    song = Song(tracks=(notes((2, 4, 60)),))
    assert 'note("<[~ c4@2 ~]@2>")' in emit(song)  # one item over 2 cycles


def test_tie_spans_are_capped_and_break_at_sections():
    # a note held across 6 bar lines: joined 4 bars at most, then re-attacked
    song = Song(tracks=(notes((2, 24, 60)),))
    assert 'note("<[~ c4@7]@4 [c4@5 ~]@3>")' in emit(song)
    # a section start always re-attacks
    song = Song(sections=(Section(0, 1, "a"), Section(1, 1, "b")), tracks=(notes((2, 4, 60)),))
    code = emit(song)
    assert 'const a = note("~ c4")' in code and 'const b = note("c4 ~")' in code


def test_ties_join_bars_but_repeats_still_collapse():
    bars = [(4 * b, 4, 60) for b in range(4)] + [(15, 2, 62)]  # d4 tied across bars 4-5
    song = DedupeBars().run(Song(tracks=(notes(*bars),)), {})
    # three equal bars still collapse; bars 4-5 are one 2-cycle item holding d4
    assert 'note("<c4!3 [c4 ~, ~ ~ ~ d4@2 ~ ~ ~]@2>")' in emit(song)


def test_drums_use_profile_map_bank_and_velocity_voices():
    song = Song(
        tracks=(
            Track(
                id="d",
                role="drums",
                events=(Hit(F(0), "kick", 120), Hit(F(2), "kick", 60), Hit(F(1), "closed_hat", 90), Hit(F(3), "closed_hat", 90)),
            ),
        )
    )
    code = emit(song)
    assert 's("bd*2").velocity("1 0.5")' in code  # each voice on its own smallest grid
    assert 's("~ hh ~ hh").velocity(0.75)' in code
    assert '.bank("RolandTR909")' in code
    lofi = emit(song, profile="lofi")
    assert '.bank("LinnDrum").lpf(3000).room(0.3).gain(0.8)' in lofi


def test_equal_velocities_are_omitted():
    track = Track(id="d", role="drums", events=(Hit(F(0), "kick", 100), Hit(F(1), "snare", 100)))
    code = emit(Song(tracks=(track,)))
    assert "velocity" not in code
    assert code.endswith('s("bd, ~ sd ~ ~").bank("RolandTR909")\n')


def test_chords_map_to_voicing_dictionary_or_fall_back():
    track = Track(
        id="c",
        role="chords",
        events=(
            Chord(F(0), F(2), "Cmaj7", root="C", quality="maj7"),
            Chord(F(2), F(2), "Bø", root="B", quality="m7b5"),
            Chord(F(4), F(4), "F/A", root="F", quality="maj", bass="A", pitches=(57, 60, 65)),
        ),
    )
    code = emit(Song(tracks=(track,)))
    assert 'chord("<[C^7 Bh7] ~>").voicing()' in code
    assert 'note("<~ [a3,c4,f4]>")' in code


def test_chord_without_voicing_or_pitches_is_an_error():
    track = Track(id="c", role="chords", events=(Chord(F(4), F(4), "Cfoo"),))
    with pytest.raises(StrudelizerError) as info:
        emit(Song(tracks=(track,)))
    assert info.value.stage == "emit:strudel"
    assert info.value.location == "track c, bar 2"
    assert "pitches" in info.value.fix


def test_bad_bars_map_is_an_error():
    track = Track(id="b", events=(Note(F(0), F(8), 60),), bars=(0,))
    with pytest.raises(StrudelizerError, match="dedupe_bars"):
        emit(Song(tracks=(track,)))


def test_sections_become_consts_and_arrange():
    track = notes((0, 4, 60), (4, 4, 62), (8, 4, 60))
    song = Song(
        sections=(Section(0, 1, "verse"), Section(1, 1, "chorus"), Section(2, 1, "verse"), Section(4, 1, "note")),
        tracks=(track,),
    )
    code = emit(song)
    assert code.count("const verse =") == 1
    assert "const part4 = silence" in code  # gap at bar 3 is filled
    assert "const note_part = silence" in code  # reserved name
    assert "arrange(\n  [1, verse],\n  [1, chorus],\n  [1, verse],\n  [1, part4],\n  [1, note_part]\n)" in code


def test_overlapping_sections_error():
    song = Song(sections=(Section(0, 2, "a"), Section(1, 2, "b")), tracks=(notes((0, 4, 60)),))
    with pytest.raises(StrudelizerError, match="overlaps"):
        emit(song)


def test_empty_song_is_silence():
    assert emit(Song(tracks=(Track(events=()),))).rstrip().endswith("silence")
